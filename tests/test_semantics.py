"""VBA and Excel behaviours, checked on small snippets.

Every test runs two ways: as structured Python generated by codegen, and as generated Python
written in numbered steps (the form a procedure takes when GoTo or On Error need it).

Run from the macropress folder:  python -m pytest
"""

import datetime as dt
import unittest

from macropress import codegen, runtime
from macropress.errors import VBACompileError, VBANotImplemented, VBARuntimeError
from macropress.excel import Book
from macropress.source import build_project

NOW = dt.datetime(2026, 1, 2, 3, 4, 5)


class Runner:
    MODE = "python"

    def run_vba(self, code, macro="Test", sheets=("Sheet1",), times=1, answers=(), modules=()):
        """Run `macro` `times` times in one session; return (Debug.Print lines, book, ledger). modules: more modules
        beside Module1, as (name, code)."""
        book = Book.blank(sheets)
        project = build_project([("Module1", code), *modules])
        source = codegen.convert(project, "test", [(None, macro)], force_flat=(self.MODE == "steps"))
        namespace = {}
        exec(compile(source, "<generated>", "exec"), namespace)
        ctx = runtime.Context(book=book, now=NOW, answers=answers)
        for _ in range(times):
            namespace[macro](ctx)
        ledger, messages = ctx.ledger, ctx.messages
        return [text for kind, text in messages if kind == "Debug.Print"], book, ledger

    def prints(self, body, **kw):
        out, _, _ = self.run_vba("Sub Test()\n" + body + "\nEnd Sub\n", **kw)
        return out


class ControlFlow(Runner):
    def test_for_counter_after_loop_is_end_plus_step(self):
        self.assertEqual(self.prints("For i = 1 To 3\nNext i\nDebug.Print i"), ["4"])

    def test_for_bounds_evaluated_once(self):
        self.assertEqual(self.prints("n = 3\nFor i = 1 To n\nn = 10\nc = c + 1\nNext\nDebug.Print c"), ["3"])

    def test_goto_out_of_loop_keeps_counter(self):
        self.assertEqual(self.prints("For i = 1 To 10\nIf i = 4 Then GoTo done\nNext\ndone:\nDebug.Print i"), ["4"])

    def test_goto_and_erase_on_their_own_lines(self):
        body = (
            "Dim a(1 To 2) As Long\na(1) = 5\nFor i = 1 To 10\nIf i = 3 Then\nGoTo done\nEnd If\nNext\n"
            "done:\nErase a\nDebug.Print i, a(1)"
        )
        self.assertEqual(self.prints(body), ["3 0"])

    def test_backward_goto(self):
        body = "i = 0\nagain:\ni = i + 1\nIf i < 3 Then GoTo again\nDebug.Print i"
        self.assertEqual(self.prints(body), ["3"])

    def test_stop_is_reported_not_skipped(self):
        with self.assertRaises(VBANotImplemented):
            self.prints("x = 1\nStop")

    def test_exit_for_and_step(self):
        self.assertEqual(self.prints("For i = 10 To 1 Step -3\nIf i < 5 Then Exit For\nNext\nDebug.Print i"), ["4"])

    def test_do_loops(self):
        body = "Do While i < 3\ni = i + 1\nLoop\nDo\ni = i + 1\nLoop Until i >= 5\nDebug.Print i"
        self.assertEqual(self.prints(body), ["5"])

    def test_select_case(self):
        body = (
            'For Each v In Array(1, 5, "x")\nSelect Case v\nCase 1, 2\nDebug.Print "low"\n'
            'Case 3 To 9\nDebug.Print "mid"\nCase Else\nDebug.Print "other"\nEnd Select\nNext'
        )
        self.assertEqual(self.prints(body), ["low", "mid", "other"])

    def test_with_block(self):
        out = self.prints('With Range("B2")\n.Value = 7\nDebug.Print .Row & "," & .Column & "," & .Value\nEnd With')
        self.assertEqual(out, ["2,2,7"])


class ErrorHandling(Runner):
    def test_resume_next_keeps_stale_value(self):
        out = self.prints("On Error Resume Next\nx = 5\nx = 1 / 0\nDebug.Print x\nDebug.Print Err.Number")
        self.assertEqual(out, ["5", "11"])

    def test_error_in_if_condition_runs_the_body(self):
        out = self.prints('On Error Resume Next\nIf 1 / 0 > 1 Then\nDebug.Print "body ran"\nEnd If')
        self.assertEqual(out, ["body ran"])

    def test_resume_next_inside_loop(self):
        body = 'On Error Resume Next\nFor i = 1 To 3\nx = 10 / (i - 2)\nDebug.Print i & ":" & x\nNext'
        self.assertEqual(self.prints(body), ["1:-10", "2:-10", "3:10"])

    def test_on_error_goto_and_resume_next(self):
        body = (
            'On Error GoTo handler\nx = 1 / 0\nDebug.Print "after"\nExit Sub\n'
            'handler:\nDebug.Print "caught " & Err.Number\nResume Next'
        )
        self.assertEqual(self.prints(body), ["caught 11", "after"])

    def test_unhandled_error_stops_the_macro(self):
        with self.assertRaises(VBARuntimeError) as ctx:
            self.prints("x = 1\ny = x / 0")
        self.assertEqual(ctx.exception.number, 11)

    def test_gaps_in_the_model_are_never_skipped(self):
        # nor passed off as a mistake in the macro: a property the model cannot set, or a VBA function it does not
        # cover, is "not modelled", which On Error does not skip
        for body in (
            'Range("A1:B3").SpecialCells(4).Select',
            'Range("A1").NumberFormat = "0.00"',
            'Set o = CreateObject("Scripting.Dictionary")',
            'Shell "notepad.exe"',
            'x = Dir("*.xlsx")',
        ):
            with self.subTest(body), self.assertRaises(VBANotImplemented):
                self.prints("On Error Resume Next\n" + body)

    def test_option_explicit(self):
        with self.assertRaises(VBACompileError):
            self.run_vba("Option Explicit\nSub Test()\nx = 1\nEnd Sub\n")


class Values(Runner):
    def test_rounding_halves_to_even(self):
        out = self.prints("Debug.Print CInt(2.5) & CInt(3.5) & CLng(-2.5) & Round(2.5) & Round(0.125, 2)")
        self.assertEqual(out, ["24-220.12"])

    def test_integer_division_and_mod(self):
        self.assertEqual(self.prints("Debug.Print 7 \\ 2, -7 Mod 3, 7.5 \\ 2"), ["3 -1 4"])

    def test_operator_precedence(self):
        self.assertEqual(self.prints('Debug.Print -2 ^ 2, 2 + 3 * 4, Not 1 = 2, "a" & 1 + 2'), ["-4 14 True a3"])

    def test_plus_with_strings(self):
        self.assertEqual(self.prints('Debug.Print "1" + 2, "a" + "b", "a" & 1 & True'), ["3 ab a1True"])

    def test_string_functions(self):
        body = (
            'Debug.Print Mid("abcdef", 2, 3), InStr("abc", "c"), InStr(2, "abcabc", "a"), '
            'Left("abc", 2), Right("abc", 2), Len("abc"), Trim("  a  "), UCase("a")'
        )
        self.assertEqual(self.prints(body), ["bcd 3 4 ab bc 3 a A"])

    def test_mid_with_invalid_start_raises(self):
        with self.assertRaises(VBARuntimeError) as ctx:
            self.prints('x = Mid("abc", 0, 1)')
        self.assertEqual(ctx.exception.number, 5)

    def test_empty_behaves_as_zero_and_blank(self):
        self.assertEqual(self.prints('Debug.Print x + 1, "[" & y & "]", z = 0, z = ""'), ["1 [] True True"])

    def test_typed_array_with_bounds(self):
        body = (
            "Dim a(3 To 5) As String\na(3) = 12\nDebug.Print TypeName(a(3)), LBound(a), UBound(a)\n"
            "On Error Resume Next\nx = a(6)\nDebug.Print Err.Number"
        )
        self.assertEqual(self.prints(body), ["String 3 5", "9"])

    def test_integer_overflow(self):
        with self.assertRaises(VBARuntimeError) as ctx:
            self.prints("Dim i As Integer\ni = 40000")
        self.assertEqual(ctx.exception.number, 6)

    def test_number_against_text_compares_without_error(self):
        out, _, ledger = self.run_vba('Sub Test()\nIf 5 < "abc" Then Debug.Print "lt"\nEnd Sub\n')
        self.assertEqual(out, ["lt"])
        self.assertIn("CMP-NUMBER-TEXT", ledger.counts)

    def test_format_rounds_halves_away_from_zero(self):
        self.assertEqual(
            self.prints('Debug.Print Format(2.5, "0"), Format(-2.5, "0"), Format(0.125, "0.00")'), ["3 -3 0.13"]
        )

    def test_chr_and_asc_use_the_windows_code_page(self):
        self.assertEqual(self.prints('Debug.Print Chr(146) = "\u2019", Asc(Chr(146)), Asc("A")'), ["True 146 65"])

    def test_vba_functions_and_numbers_read_as_vba_reads_them(self):
        body = (
            'Debug.Print Right("abc", 5), Val("Infrastructure"), Val("1_000"), Val(" 1 2 3"), Val("&HFFFF"), '
            '&HFFFFFFFF, &H8000, DateDiff("h", TimeSerial(10, 59, 0), TimeSerial(11, 1, 0))'
        )
        self.assertEqual(self.prints(body), ["abc 0 1 123 -1 -1 -32768 1"])
        with self.assertRaises(VBARuntimeError) as ctx:  # a Double too big: VBA stops where Python would give inf
            self.prints("x = 1E+308 * 10")
        self.assertEqual(ctx.exception.number, 6)

    def test_time_passes_only_as_the_macro_waits_for_it(self):
        body = (
            "t = Timer\nn = 0\nDo While Timer < t + 1\nn = n + 1\nLoop\n"
            "Application.Wait Now + TimeSerial(0, 0, 5)\nDebug.Print n > 900, n < 1100, Second(Now)"
        )
        self.assertEqual(self.prints(body), ["True True 11"])


class Procedures(Runner):
    def test_byref_is_the_default(self):
        code = (
            "Sub Inc(x)\nx = x + 1\nEnd Sub\n"
            "Sub Test()\nn = 1\nInc n\nDebug.Print n\nInc (n)\nDebug.Print n\nCall Inc(n)\nDebug.Print n\nEnd Sub\n"
        )
        out, _, _ = self.run_vba(code)
        self.assertEqual(out, ["2", "2", "3"])

    def test_function_return_value(self):
        code = "Function Twice(v)\nTwice = v * 2\nEnd Function\nSub Test()\nDebug.Print Twice(21)\nEnd Sub\n"
        out, _, _ = self.run_vba(code)
        self.assertEqual(out, ["42"])

    def test_module_variables_persist_between_macros(self):
        code = "Dim counter As Long\nSub Test()\ncounter = counter + 1\nDebug.Print counter\nEnd Sub\n"
        out, _, _ = self.run_vba(code, times=2)
        self.assertEqual(out, ["1", "2"])

    def test_a_question_is_answered_by_its_word_or_its_number(self):
        body = 'Debug.Print MsgBox("Sure?", vbYesNo)\nDebug.Print MsgBox("Again?", vbYesNo)'
        self.assertEqual(self.prints(body, answers=["yes", "7"]), ["6", "7"])

    def test_a_module_keeps_its_own_option_compare_and_its_own_sheet(self):
        code = (
            'Option Compare Text\nSub Test()\nDebug.Print InStr("ABC", "b")\nHelper\n'
            'Debug.Print InStr("ABC", "b"), "a" = "A"\nSheets("S1").Activate\nSheet2.Fill\n'
            'Sheet2.Range("B1").Value = "by code name"\nEnd Sub\n'
        )
        helper = ("Module2", 'Sub Helper()\nDebug.Print InStr("ABC", "b"), "a" = "A"\nEnd Sub\n')
        sheet2 = (
            "Sheet2",
            'Attribute VB_Name = "Sheet2"\nAttribute VB_Base = "0{00020820-0000-0000-C000-000000000046}"\n'
            'Sub Fill()\nRange("A1").Value = Me.Name\nEnd Sub\n',
        )
        out, book, _ = self.run_vba(code, modules=[helper, sheet2], sheets=("S1", "S2"))
        self.assertEqual(out, ["2", "0 False", "2 True"])  # a call into a Binary module leaves this one Text
        s1, s2 = book.find_sheet("S1"), book.find_sheet("S2")  # in Sheet2's module, Range is Sheet2's
        self.assertEqual((s2.rows[1][1].value, s2.rows[1][2].value, s1.rows), ("S2", "by code name", {}))


class ExcelModel(Runner):
    def test_writing_and_reading_cells(self):
        body = (
            'Range("A1").Value = "123"\nRange("A2").Value = "\'007"\nCells(3, 1) = True\n'
            'Debug.Print TypeName(Range("A1").Value), Range("A2").Value, TypeName(Cells(3, 1).Value)'
        )
        self.assertEqual(self.prints(body), ["Double 007 Boolean"])

    def test_end_and_current_region(self):
        body = (
            'Range("A1:A5").Value = 1\nRange("A8").Value = 1\n'
            'Debug.Print Range("A1").End(xlDown).Row, Range("A5").End(xlDown).Row, '
            'Range("A6").End(xlDown).Row, Range("A8").End(xlDown).Row, Range("A3").CurrentRegion.Address'
        )
        self.assertEqual(self.prints(body), ["5 8 8 1048576 $A$1:$A$5"])

    def test_filter_copy_paste_visible_rows(self):
        body = (
            'Range("A1").Value = "Key"\nRange("B1").Value = "Val"\n'
            'For i = 2 To 6\nCells(i, 1) = IIf(i Mod 2 = 0, "x", "y")\nCells(i, 2) = i\nNext\n'
            'Range("A1:B6").AutoFilter Field:=1, Criteria1:="X"\n'
            'Range("A1:B6").Copy\nSheets("Out").Select\nRange("A1").Select\n'
            "Selection.PasteSpecial Paste:=xlPasteValues\n"
            'Debug.Print Sheets("Out").Range("B2").Value & "," & Sheets("Out").Range("B3").Value & "," & '
            'Sheets("Out").Range("B4").Value & "," & IsEmpty(Sheets("Out").Range("B5").Value)'
        )
        self.assertEqual(self.prints(body, sheets=("Sheet1", "Out")), ["2,4,6,True"])

    def test_grouped_clear_contents(self):
        body = (
            'Sheets("S2").Range("A2").Value = 1\nSheets("S3").Range("A2").Value = 1\n'
            'Sheets(Array("S1", "S2")).Select\nRange("A1:B5").Select\nSelection.ClearContents\n'
            'Debug.Print IsEmpty(Sheets("S2").Range("A2").Value), IsEmpty(Sheets("S3").Range("A2").Value)'
        )
        self.assertEqual(self.prints(body, sheets=("S1", "S2", "S3")), ["True False"])

    def test_select_on_inactive_sheet_fails(self):
        with self.assertRaises(VBARuntimeError) as ctx:
            self.prints('Sheets("S2").Range("A1").Select', sheets=("S1", "S2"))
        self.assertEqual(ctx.exception.number, 1004)

    def test_missing_sheet_is_error_9(self):
        with self.assertRaises(VBARuntimeError) as ctx:
            self.prints('Sheets("Nope").Select')
        self.assertEqual(ctx.exception.number, 9)

    def test_worksheetfunction_find_raises_when_not_found(self):
        out = self.prints(
            'On Error Resume Next\nx = Application.WorksheetFunction.Find("z", "abc")\nDebug.Print Err.Number'
        )
        self.assertEqual(out, ["1004"])

    def test_lookups_past_the_data_read_blank(self):
        body = (
            'Range("A1").Value = "a"\nRange("B1").Value = 1\n'
            'Range("F1").Formula = "=VLOOKUP(""a"",A1:D1,4,FALSE)"\nRange("F2").Formula = "=INDEX(A1:D3,3,4)"\n'
            'Debug.Print Range("F1").Value, Range("F2").Value'
        )
        self.assertEqual(self.prints(body), ["0 0"])

    def test_left_and_right_refuse_a_negative_length_and_stop_at_the_text(self):
        body = (
            'Range("A1").Formula = "=LEFT(""abc"",-1)"\nRange("A2").Formula = "=RIGHT(""abc"",-1)"\n'
            'Range("A3").Formula = "=RIGHT(""abc"",5)"\n'
            'Debug.Print CStr(Range("A1").Value), CStr(Range("A2").Value), Range("A3").Value'
        )
        self.assertEqual(self.prints(body), ["Error 2015 Error 2015 abc"])

    def test_address_with_a_relative_row_or_column(self):
        body = 'Debug.Print Range("C5").Address(False, True), Range("C5").Address(True, False)'
        self.assertEqual(self.prints(body), ["$C5 C$5"])

    def test_an_error_value_used_as_text_is_a_type_mismatch(self):
        body = 'Range("A1").Formula = "=1/0"\nDebug.Print CStr(Range("A1").Value), IsError(Range("A1").Value)'
        self.assertEqual(self.prints(body), ["Error 2007 True"])
        with self.assertRaises(VBARuntimeError) as ctx:
            self.prints('Range("A1").Formula = "=1/0"\nx = Range("A1").Value & "-x"')
        self.assertEqual(ctx.exception.number, 13)

    def test_functions_read_cells_as_excel_does(self):
        body = (
            'Range("A1").Value = DateSerial(2024, 1, 5)\nRange("A2").Value = DateSerial(2023, 1, 5)\n'
            'Debug.Print Application.WorksheetFunction.Max(Range("A1:A2"))\n'
            'Range("B1").Formula = "=1/0"\nRange("B2").Value = "x"\nRange("C2").Value = "y"\n'
            'Range("D1").Formula = "=VLOOKUP(""x"",B1:C2,2,)"\nRange("D2").Formula = "=IF(TRUE,,1)"\n'
            'Range("E1").Value = 1\nRange("E2").Value = True\nRange("F1").Formula2 = "=UNIQUE(E1:E2)"\n'
            'Range("G1").Formula = "=1E+308*10"\n'
            'Range("H1").Formula = "=SUM(E1:E2)"\nRange("H2").Formula = "=H1*2"\nRange("H3").Formula = "=H1*3"\n'
            'Debug.Print Range("D1").Value, Range("D2").Value, Range("F2").Value, CStr(Range("G1").Value)\n'
            'Debug.Print Application.WorksheetFunction.XLookup(Range("B2"), Range("B1:B2"), Range("C1:C2"))\n'
            'Debug.Print Range("H2").Value, Range("H3").Value\n'
            'On Error Resume Next\nx = Application.WorksheetFunction.Sum(Range("A1:B2"))\nDebug.Print Err.Number'
        )
        # dates are numbers to a worksheet function, a lookup skips an error cell, an empty argument is blank (0 or
        # FALSE), TRUE and 1 are two values, a number too big is #NUM!, formulas that read a stale SUM get its value
        # (not a circular reference), and an error stops Sum (error 1004)
        self.assertEqual(self.prints(body), ["45296", "y 0 True Error 2036", "y", "2 3", "1004"])
        lookup = 'Dim a()\nx = Application.WorksheetFunction.XLookup({}, Range("B1:B2"), Range("C1:C2"))'
        for value in ("a", 'Range("B1:B2")'):  # an empty array, and two cells: Excel would return an array of results
            with self.assertRaises(VBANotImplemented):
                self.prints(lookup.format(value))

    def test_clearing_filtering_and_renaming_as_excel_does(self):
        body = (
            'Range("A1:A2").Value = DateSerial(2024, 1, 5)\nRange("A1").ClearContents\nRange("A2").Clear\n'
            'Range("A1:A2").Value = 45000\nDebug.Print TypeName(Range("A1").Value), TypeName(Range("A2").Value)\n'
            'Range("C1").Value = "k"\nRange("C2").Value = "b"\nRange("C3").Value = "a"\nRange("C4").Value = "b"\n'
            'Range("C1:D1").AutoFilter Field:=1, Criteria1:="a"\n'
            "Debug.Print Rows(2).Hidden, Rows(3).Hidden, Rows(4).Hidden\n"
            'Range("E1").Formula = "=Other!A1*2"\nSheets("Other").Name = "Renamed"\n'
            'Sheets("Renamed").Range("A1").Value = 10\nDebug.Print Range("E1").Formula, Range("E1").Value'
        )
        # ClearContents keeps a cell's date format and Clear doesn't, a header row's filter covers the rows below,
        # and a renamed sheet is renamed in the formulas that read it
        expected = ["Date Double", "True False True", "=Renamed!A1*2 20"]
        self.assertEqual(self.prints(body, sheets=("Data", "Other")), expected)
        with self.assertRaises(VBARuntimeError) as ctx:  # a name Excel refuses
            self.prints('Sheets(1).Name = "a/b"')
        self.assertEqual(ctx.exception.number, 1004)


class MovingFormulas(Runner):
    """A formula filled, pasted or sorted into another cell: its relative references move with it, wherever they
    point, and only they do."""

    def test_fill_paste_and_sort_move_every_relative_reference(self):
        body = (
            'Range("D5:E6").Formula = "=Other!A1+\'My sheet\'!$A1+SUM(A:A)+SUM($1:1)+LEN(""A1"")"\n'
            'Range("B2").Formula = "=Other!A1*2"\nRange("B2").Copy Range("D9")\n'
            'Sheets("Other").Range("C1").Value = 10\nSheets("Other").Range("C2").Value = 20\n'
            'Range("G1").Value = 2\nRange("G2").Value = 1\nRange("H1").Formula = "=Other!C1"\n'
            'Range("H2").Formula = "=Other!C2"\nRange("G1:H2").Sort Key1:=Range("G1"), Order1:=xlAscending, Header:=xlNo\n'
            'Range("J20:L20").Value = 2\nRange("J21").Formula = "=SUM(20:20)"\n'
            'Debug.Print Range("E6").Formula\nDebug.Print Range("D9").Formula, Range("H1").Formula, Range("H1").Value\n'
            'Debug.Print Range("J21").Value'
        )
        out = self.prints(body, sheets=("Sheet1", "Other", "My sheet"))
        expected = [  # whole columns and rows move too, and a whole row is read
            "=Other!B2+'My sheet'!$A2+SUM(B:B)+SUM($1:2)+LEN(\"A1\")",
            "=Other!C8*2 =Other!C1 10",
            "6",
        ]
        self.assertEqual(out, expected)

    def test_moving_off_the_sheet_or_into_another_size_is_refused(self):
        for body in (
            'Range("B1").Formula = "=A1"\nRange("B1").Copy Range("A1")',
            'Range("A2").Formula = "=A1"\nRange("A2").Copy Range("B1")',
            'Range("A1:A2").Formula = "=A1048576"',
        ):
            with self.assertRaisesRegex(VBANotImplemented, "would leave the sheet"):
                self.prints(body)
        with self.assertRaises(VBARuntimeError) as ctx:
            self.prints('Range("A1:B1").Value = 1\nRange("A1:B1").Copy Range("XFD1")')
        self.assertEqual(ctx.exception.number, 1004)
        with self.assertRaisesRegex(VBANotImplemented, "another size"):
            self.prints('Range("A1").Value = 1\nRange("A1").Copy Range("B1:B3")')


GROUPS = [ControlFlow, ErrorHandling, Values, Procedures, ExcelModel, MovingFormulas]
for _group in GROUPS:
    for _mode, _suffix in (("python", "GeneratedPython"), ("steps", "GeneratedSteps")):
        _name = f"{_group.__name__}_{_suffix}"
        globals()[_name] = type(_name, (_group, unittest.TestCase), {"MODE": _mode})
del _group, _mode, _suffix, _name


if __name__ == "__main__":
    unittest.main()
